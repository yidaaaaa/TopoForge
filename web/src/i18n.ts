const dictionaries: Record<Language, Record<TranslationKey, string>> = {
  "zh-CN": zh,
  en,
};

export function translate(language: Language, key: TranslationKey): string {
  return dictionaries[language][key];
}

export function jobStateKey(state: string): TranslationKey {
  const key = `jobState${state.charAt(0).toUpperCase()}${state.slice(1)}`;
  return key as TranslationKey;
}

export function stageKey(stage: string | null): TranslationKey | null {
  if (!stage) {
    return null;
  }
  const key = `stage${stage.charAt(0).toUpperCase()}${stage.slice(1)}`;
  return key as TranslationKey;
}
